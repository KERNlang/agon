import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const evidenceDir = resolve(process.env.AGON_SPEC_EVIDENCE_DIR || resolve(root, 'docs/specs/evidence'));
const generatedDir = resolve(process.env.AGON_SPEC_GENERATED_DIR || resolve(root, 'packages/mod-kernel/src/generated'));
const inventoryPath = resolve(evidenceDir, 'modular-agon-current-inventory.json');
const ownershipPath = resolve(evidenceDir, 'modular-agon-ownership.json');
const outputPath = resolve(generatedDir, 'legacy-surface-catalog.ts');

const inventory = JSON.parse(readFileSync(inventoryPath, 'utf8'));
const ownership = JSON.parse(readFileSync(ownershipPath, 'utf8'));
const assignmentByOccurrence = new Map(ownership.assignments.map((assignment) => [
  [assignment.category, assignment.id, assignment.source].join('\0'),
  assignment,
]));

const surfaceCategories = {
  cliCommands: { surface: 'cli', kind: 'cli-command' },
  tuiSlashCommands: { surface: 'tui', kind: 'tui-action' },
  tuiKeyboardActions: { surface: 'tui', kind: 'tui-action' },
  builtinCommandMetadata: { surface: 'tui', kind: 'tui-action' },
  intentVariants: { surface: 'tui', kind: 'intent' },
  mcpTools: { surface: 'mcp', kind: 'mcp-tool' },
  cesarTools: { surface: 'cesar', kind: 'cesar-tool' },
  cesarRoutes: { surface: 'cesar', kind: 'cesar-tool' },
  generatedDocumentation: { surface: 'docs', kind: 'docs' },
};

const compareAscii = (left, right) => left < right ? -1 : left > right ? 1 : 0;

function ownerModId(packageName) {
  const id = packageName === '@kernlang/agon-kernel'
    ? 'agon.kernel'
    : 'agon.' + packageName.replace(/^@kernlang\/agon-(?:mod-|support-)?/, '').replace(/[^a-z0-9]+/g, '-');
  if (!/^agon\.[a-z0-9]+(?:[.-][a-z0-9]+)*$/.test(id)) throw new Error('invalid generated owner ID: ' + id);
  return id;
}

const ownerHashByPackage = new Map();
for (const packageName of [...new Set(ownership.assignments.map((assignment) => assignment.package))].sort(compareAscii)) {
  const owned = ownership.assignments
    .filter((assignment) => assignment.package === packageName)
    .map(({ category, id, source, class: ownerClass }) => ({ category, id, source, ownerClass }))
    .sort((left, right) => compareAscii(left.category, right.category)
      || compareAscii(left.id, right.id)
      || compareAscii(left.source, right.source));
  ownerHashByPackage.set(packageName, 'sha256:' + createHash('sha256').update(JSON.stringify({ packageName, owned })).digest('hex'));
}

const entries = [];
for (const [category, projection] of Object.entries(surfaceCategories)) {
  const occurrences = inventory.categories[category];
  occurrences.forEach((occurrence, index) => {
    const assignment = assignmentByOccurrence.get([category, occurrence.id, occurrence.source].join('\0'));
    if (!assignment) throw new Error(`missing ownership: ${category}/${occurrence.id}/${occurrence.source}`);
    entries.push({
      surface: projection.surface,
      kind: projection.kind,
      id: `${category}:${String(index).padStart(4, '0')}`,
      owner: {
        id: ownerModId(assignment.package),
        version: '0.2.5-legacy-compat',
        contentHash: ownerHashByPackage.get(assignment.package),
      },
      payload: {
        publicId: occurrence.id,
        category,
        source: occurrence.source,
        ownerPackage: assignment.package,
        ownerClass: assignment.class,
        aliasOf: occurrence.aliasOf ?? null,
        compatibility: true,
      },
    });
  });
}

entries.sort((left, right) => compareAscii(left.surface, right.surface)
  || compareAscii(left.kind, right.kind)
  || compareAscii(left.id, right.id));

const source = `/** Generated by scripts/spec/generate-modular-agon-compat-projections.mjs. Do not edit. */\nexport const LEGACY_SURFACE_CATALOG = ${JSON.stringify(entries, null, 2)} as const;\n`;
if (process.argv.includes('--check')) {
  const current = readFileSync(outputPath, 'utf8');
  if (current !== source) {
    console.error('legacy surface catalog is stale; regenerate it');
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, source);
  console.log(`generated ${entries.length} owner-tagged surface occurrences`);
}
