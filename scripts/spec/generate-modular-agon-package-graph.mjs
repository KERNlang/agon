import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const evidenceDir = resolve(process.env.AGON_SPEC_EVIDENCE_DIR || resolve(root, 'docs/specs/evidence'));
const generatedDir = resolve(process.env.AGON_SPEC_GENERATED_DIR || resolve(root, 'packages/mod-kernel/src/generated'));
const inputPath = resolve(evidenceDir, 'modular-agon-package-map.json');
const outputPath = resolve(generatedDir, 'first-party-package-graph.ts');
const uiInputPath = resolve(evidenceDir, 'modular-agon-ui-hierarchy.json');
const uiOutputPath = resolve(generatedDir, 'first-party-ui-hierarchy.ts');
const graph = JSON.parse(readFileSync(inputPath, 'utf8'));
const ui = JSON.parse(readFileSync(uiInputPath, 'utf8'));
const expectedEdges = graph.packages.flatMap((entry) => entry.dependencies.map((dependency) => ({
  from: entry.id, to: dependency, kind: 'hard',
})));
if (JSON.stringify(graph.dependencyEdges) !== JSON.stringify(expectedEdges)) {
  throw new Error('dependencyEdges contradict package dependencies');
}

const source = `/** Generated by scripts/spec/generate-modular-agon-package-graph.mjs. Do not edit. */\nexport const FIRST_PARTY_PACKAGE_GRAPH = ${JSON.stringify(graph, null, 2)} as const;\n`;
const uiSource = `/** Generated from docs/specs/evidence/modular-agon-ui-hierarchy.json. Do not edit. */\nexport const FIRST_PARTY_UI_HIERARCHY = ${JSON.stringify(ui, null, 2)} as const;\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(outputPath, 'utf8') !== source) {
    console.error('first-party package graph is stale; regenerate it');
    process.exitCode = 1;
  }
  if (readFileSync(uiOutputPath, 'utf8') !== uiSource) {
    console.error('first-party UI hierarchy is stale; regenerate it');
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, source);
  writeFileSync(uiOutputPath, uiSource);
  console.log(`generated ${graph.packages.length} packages and ${graph.dependencyEdges.length} dependency edges`);
}
